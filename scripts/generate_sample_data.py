"""Generate the sample raw dataset used by the pipeline.

The output is fully deterministic (fixed seed), so the committed files in
``data/raw/`` can be regenerated byte-for-byte:

    python scripts/generate_sample_data.py

The data imitates two exports from an e-commerce system:

* ``customers.jsonl`` - one JSON object per line (CRM export, nested address)
* ``orders.csv``      - order lines (order system export)

Realistic defects are injected at known rates so the cleaning and validation
stages have something to do. The defect catalogue is documented in
``docs/DATA.md``.
"""

from __future__ import annotations

import argparse
import csv
import json
import random
from datetime import date, datetime, timedelta
from pathlib import Path

SEED = 42
N_CUSTOMERS = 400
N_ORDERS = 3000

FIRST = ["Aarav", "Priya", "Liam", "Emma", "Noah", "Olivia", "Rohan", "Ananya",
         "Lucas", "Mia", "Arjun", "Sofia", "Ethan", "Isha", "Mateo", "Zara"]
LAST = ["Sharma", "Patel", "Smith", "Johnson", "Garcia", "Mueller", "Rossi",
        "Kumar", "Brown", "Lee", "Martin", "Singh", "Lopez", "Nair"]
CITIES = {"US": ["Austin", "Seattle", "Boston"], "IN": ["Pune", "Bengaluru", "Delhi"],
          "DE": ["Berlin", "Munich"], "GB": ["London", "Leeds"]}
# Messy spellings of the same country, as found in hand-entered CRM data.
COUNTRY_VARIANTS = {
    "US": ["US", "us", "USA", "United States", "U.S."],
    "IN": ["IN", "in", "India", "INDIA"],
    "DE": ["DE", "Germany", "deutschland"],
    "GB": ["GB", "UK", "United Kingdom"],
}
CURRENCY_BY_COUNTRY = {"US": "USD", "IN": "INR", "DE": "EUR", "GB": "GBP"}
SKUS = {f"SKU-{i:03d}": round(random.Random(i).uniform(5, 400), 2) for i in range(1, 41)}
STATUS_VARIANTS = {
    "pending": ["pending", "Pending", "PENDING"],
    "shipped": ["shipped", "Shipped", "SHIPPED ", " shipped"],
    "delivered": ["delivered", "Delivered", "DELIVERED"],
    "cancelled": ["cancelled", "canceled", "Cancelled"],
    "returned": ["returned", "Returned"],
}


def fmt_date(rng: random.Random, d: date) -> str:
    """Render a date in one of the formats seen across source systems."""
    choice = rng.random()
    if choice < 0.70:
        return d.isoformat()                    # 2025-03-14
    if choice < 0.88:
        return d.strftime("%m/%d/%Y")           # 03/14/2025 (US export)
    return d.strftime("%d %b %Y")               # 14 Mar 2025


def rand_date(rng: random.Random, start: date, end: date) -> date:
    return start + timedelta(days=rng.randint(0, (end - start).days))


def make_customers(rng: random.Random) -> tuple[list[str], dict[str, date]]:
    lines: list[str] = []
    signup: dict[str, date] = {}
    for i in range(1, N_CUSTOMERS + 1):
        cid = f"C{i:05d}"
        country = rng.choice(list(CITIES))
        first, last = rng.choice(FIRST), rng.choice(LAST)
        d = rand_date(rng, date(2023, 1, 1), date(2025, 6, 30))
        signup[cid] = d
        rec = {
            "customer_id": cid,
            "name": f"{first} {last}",
            "email": f"{first}.{last}{i}@example.com".lower(),
            "signup_date": fmt_date(rng, d),
            "address": {"city": rng.choice(CITIES[country]),
                        "country": rng.choice(COUNTRY_VARIANTS[country])},
            "updated_at": datetime(2025, 7, 1, 9, 0).isoformat(),
        }
        r = rng.random()
        if r < 0.08:
            rec["email"] = "  " + rec["email"].upper() + " "     # case / whitespace
        elif r < 0.10:
            rec["email"] = rng.choice([f"{first}.{last}@", "not-an-email", ""])
        if rng.random() < 0.02:
            rec["name"] = None                                   # missing name
        if rng.random() < 0.05:
            rec["customer_id"] = f" {cid.lower()} "              # id formatting
        if rng.random() < 0.01:
            rec["customer_id"] = None                            # missing key
        if rng.random() < 0.02:
            rec["signup_date"] = rng.choice(["unknown", "31/31/2024"])
        lines.append(json.dumps(rec))

        if rng.random() < 0.03:                                  # exact duplicate
            lines.append(json.dumps(rec))
        if rng.random() < 0.04 and rec["customer_id"]:           # later correction
            newer = dict(rec)
            newer["email"] = f"{first}.{last}.new{i}@example.com".lower()
            newer["updated_at"] = datetime(2025, 9, 15, 14, 30).isoformat()
            lines.append(json.dumps(newer))

    # A truncated write and a stray non-object line from the export job.
    lines.insert(57, '{"customer_id": "C09999", "name": "Broken Rec')
    lines.insert(211, '["not", "an", "object"]')
    return lines, signup


def make_orders(rng: random.Random, signup: dict[str, date]) -> list[list[str]]:
    header = ["order_id", "customer_id", "order_date", "sku", "quantity",
              "unit_price", "currency", "status", "updated_at"]
    rows: list[list[str]] = [header]
    cids = list(signup)
    for i in range(1, N_ORDERS + 1):
        oid = f"O{i:06d}"
        cid = rng.choice(cids)
        sku = rng.choice(list(SKUS))
        country_ccy = rng.choice(list(CURRENCY_BY_COUNTRY.values()))
        d = rand_date(rng, max(signup[cid], date(2025, 1, 1)), date(2026, 9, 30))
        qty = str(rng.choice([1, 1, 1, 2, 2, 3, 4, 5]))
        price = SKUS[sku]
        price_s = f"{price:.2f}"
        status = rng.choice(rng.choice(list(STATUS_VARIANTS.values())))
        ccy = country_ccy
        updated = datetime.combine(d, datetime.min.time()) + timedelta(hours=rng.randint(1, 48))

        r = rng.random()
        if r < 0.05:
            price_s = f"${price:,.2f}"                    # currency symbol
        elif r < 0.08:
            price_s = f" {price} "                        # whitespace, 1 dp
        elif r < 0.09:
            price_s = ""                                  # missing
        elif r < 0.095:
            price_s = "N/A"                               # junk
        elif r < 0.10:
            price_s = f"-{price:.2f}"                     # negative
        r = rng.random()
        if r < 0.03:
            qty = qty + ".0"                              # float-formatted int
        elif r < 0.04:
            qty = rng.choice(["0", "-1", "", "two"])      # invalid
        r = rng.random()
        if r < 0.05:
            ccy = ccy.lower()
        elif r < 0.07:
            ccy = ""                                      # missing currency
        elif r < 0.075:
            ccy = "XYZ"                                   # unknown currency
        r = rng.random()
        if r < 0.01:
            status = rng.choice(["lost?", "unknown", ""])
        date_s = fmt_date(rng, d)
        r = rng.random()
        if r < 0.01:
            date_s = rng.choice(["not a date", "2025-13-45"])
        elif r < 0.015:
            date_s = "2031-01-01"                         # future date
        r = rng.random()
        if r < 0.015:
            cid = f"C{rng.randint(90000, 90999):05d}"     # orphan customer
        elif r < 0.05:
            cid = f" {cid.lower()}"
        if rng.random() < 0.005:
            oid = ""                                      # missing key

        row = [oid, cid, date_s, sku, qty, price_s, ccy, status, updated.isoformat()]
        rows.append(row)

        if rng.random() < 0.03:                           # exact duplicate row
            rows.append(list(row))
        if oid and rng.random() < 0.04:                   # status update, re-exported
            newer = list(row)
            newer[7] = rng.choice(["delivered", "returned", "cancelled"])
            newer[8] = (updated + timedelta(days=3)).isoformat()
            rows.append(newer)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="data/raw", help="output directory")
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    rng = random.Random(SEED)
    customer_lines, signup = make_customers(rng)
    order_rows = make_orders(rng, signup)

    (out / "customers.jsonl").write_text("\n".join(customer_lines) + "\n", encoding="utf-8")
    with open(out / "orders.csv", "w", newline="", encoding="utf-8") as fh:
        csv.writer(fh).writerows(order_rows)
    print(f"wrote {len(customer_lines)} customer lines and {len(order_rows) - 1} order rows to {out}/")


if __name__ == "__main__":
    main()
